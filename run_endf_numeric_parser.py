def fmt(x):
    if isinstance(x, (float, np.floating)):
        return f"{float(x):.6e}"
    return str(x)


def fmt_pair(t):
    return f"({fmt(t[0])}, {fmt(t[1])})"


def print_parsed(d: dict) -> None:
    print("== MF=8, MT=457 Radioactive Decay Data ==")
    for key in ("ZA", "AWR", "LIS", "LISO", "NST", "NSP"):
        print(f"{key}: {fmt(d.get(key))}")

    if d.get("NST") == 1:
        print(f"SPI: {fmt(d.get('SPI'))}")
        print(f"PAR: {fmt(d.get('PAR'))}")
        return

    print(f"T1/2: {fmt_pair(d['T1/2'])}")
    print(f"NC: {d['NC']}")
    if d.get("Ex"):
        print("Ex levels (value, uncertainty):")
        for i, (v, u) in enumerate(d["Ex"], 1):
            print(f"  Ex[{i}]: {fmt(v)} ± {fmt(u)}")

    print(f"SPI: {fmt(d.get('SPI'))}")
    print(f"PAR: {fmt(d.get('PAR'))}")

    print(f"NDK (num decay modes): {d.get('NDK')}")
    for i, m in enumerate(d.get("modes", []), 1):
        print(f"  Mode[{i}]: RTYP={fmt(m['RTYP'])}, RFS={fmt(m['RFS'])}, Q={fmt_pair(m['Q'])}, BR={fmt_pair(m['BR'])}")

    for si, s in enumerate(d.get("spectra", []), 1):
        print(f"Spectrum[{si}]: STYP={s['STYP']}, LCON={s['LCON']}, LCOV={s['LCOV']}, NER={s['NER']}")
        print(f"  FD: {fmt_pair(s['FD'])}")
        print(f"  ER_AV: {fmt_pair(s['ER_AV'])}")
        print(f"  FC: {fmt_pair(s['FC'])}")
        if 'discrete' in s:
            print("  Discrete emissions:")
            for di, de in enumerate(s['discrete'], 1):
                print(f"    d[{di}] ER={fmt_pair(de['ER'])} RTYP={fmt(de['RTYP'])} TYPE={fmt(de['TYPE'])}")
                if 'RI' in de:
                    print(f"      RI={fmt_pair(de['RI'])} RIS={fmt_pair(de['RIS'])}")
                    print(f"      RICC={fmt_pair(de['RICC'])} RICK={fmt_pair(de['RICK'])} RICL={fmt_pair(de['RICL'])}")
        if 'continuous' in s:
            rp = s['continuous']['RP']
            print(f"  Continuous: RTYP={fmt(s['continuous']['RTYP'])} RP points={len(rp.x)}")
        if 'continuous_covariance' in s:
            cc = s['continuous_covariance']
            print(f"  Continuous covariance: LB={cc['LB']} Ek[{cc['Ek'].size}] Fk[{cc['Fk'].size}]")
        if 'discrete_covariance' in s:
            dc = s['discrete_covariance']
            print(f"  Discrete covariance: LS={dc['LS']} LB={dc['LB']} NE={dc['NE']} NERP={dc['NERP']}")
            print(f"    Ek[{dc['Ek'].size}] Fkk[{dc['Fkk'].size}]")


